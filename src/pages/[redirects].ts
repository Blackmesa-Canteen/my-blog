import { getCollection } from 'astro:content';

/**
 * Generates Cloudflare's `_redirects` file (a leading underscore would make
 * Astro skip a page file, hence the dynamic route). Old Halo permalinks
 * (`original_permalink` in frontmatter) get a permanent redirect to the
 * post's current URL, so existing links and search rankings carry over.
 */
export async function getStaticPaths() {
  return [{ params: { redirects: '_redirects' } }];
}

export async function GET() {
  const entries = [...(await getCollection('posts')), ...(await getCollection('pages'))];
  const prefix = (entry: (typeof entries)[number]) => (entry.collection === 'posts' ? '/posts/' : '/');
  const rules = entries
    .filter((entry) => entry.data.original_permalink)
    .map((entry) => [entry.data.original_permalink!, `${prefix(entry)}${encodeURIComponent(entry.id)}/`])
    // About and Tea House kept their old paths.
    .filter(([from, to]) => from.replace(/\/$/, '') !== to.replace(/\/$/, ''))
    .sort(([a], [b]) => a.localeCompare(b));

  const lines = [
    '# Generated by src/pages/[redirects].ts at build time; do not edit by hand.',
    '',
    '# Halo-era list page and feeds',
    '/archives /archive/ 301',
    '/archives/ /archive/ 301',
    '/feed /rss.xml 301',
    '/feed.xml /rss.xml 301',
    '/atom.xml /rss.xml 301',
    '',
    '# Halo-era post permalinks, with and without a trailing slash',
    ...rules.flatMap(([from, to]) => [`${from} ${to} 301`, `${from}/ ${to} 301`]),
    '',
    // Cloudflare's own slash redirect is a 307 (temporary); make it permanent.
    '# Add the trailing slash with a permanent redirect',
    ...['/about', '/tea-house', '/archive', '/search', '/tags'].map((path) => `${path} ${path}/ 301`),
    ...['/posts/:slug', '/page/:page', '/tags/:tag', '/categories/:category'].map((path) => `${path} ${path}/ 301`),
    '',
  ];
  return new Response(lines.join('\n'), { headers: { 'Content-Type': 'text/plain; charset=utf-8' } });
}
